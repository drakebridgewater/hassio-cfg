#!/usr/bin/env python3
"""Write each room page's alert chips from the badges on its Home room card.

The Home room cards (sections/spaces-cards/*/) show their alerts as icon-only Bubble badges.
This copies the same badges (icon, colour, condition) into sections/rooms/<room>/01-alerts.yaml
as a labelled chip row, so the room page says what the badges on the card meant. Chips show
only while their condition holds, like the badges.

    python3 dashboards/tools/gen_room_alerts.py

Edit the badges in the room card, then re-run. Plain text parsing: no PyYAML needed.
"""
import re
from pathlib import Path

DASH = Path(__file__).resolve().parents[1]
MARKER = "# Generated by dashboards/tools/gen_room_alerts.py from the room card's badges.\n"


def badges(text):
    """Yield (name, icon, color, condition_lines) for each badge in a room card file."""
    body = text.split("  - badges:\n", 1)[1]
    for block in re.split(r"(?m)^      - name: ", body)[1:]:
        lines = block.splitlines()
        name = lines[0].strip()
        icon = re.search(r"(?m)^        icon: (\S+)", block).group(1)
        color = re.search(r"(?m)^        color: (\S+)", block).group(1)
        cond = block.split("        condition:\n", 1)[1].splitlines()
        yield name, icon, color, [l for l in cond if l.strip() and not l.lstrip().startswith("#")]


def render(items):
    out = [MARKER, "type: custom:bubble-card\ncard_type: sub-buttons\nsub_button:\n  main: []\n  bottom:\n"
           "    - name: Alerts\n      buttons_layout: inline\n      justify_content: start\n      group:\n"]
    css = []
    for i, (name, icon, color, cond) in enumerate(items, 1):
        out.append(f"        - name: {name}\n          icon: {icon}\n          show_name: true\n"
                   f"          fill_width: false\n          tap_action:\n            action: none\n"
                   f"          visibility:\n")
        out += [f"  {l}\n" for l in cond]
        css.append(f"      .bubble-sub-button-{i} ha-icon {{ background: var(--{color}-color); color: #fff !important;\n"
                   f"        border-radius: 50%; padding: 4px; --mdc-icon-size: 16px; box-sizing: content-box; }}\n")
    out.append("styles: |-\n" + "".join(css))
    out.append("view_layout:\n  grid-column: 1 / -1\n")
    return "".join(out)


for card in sorted((DASH / "sections/spaces-cards").glob("*/*.yaml")):
    text = card.read_text()
    m = re.search(r"- popup: /lovelace-main/(\S+)", text)
    room_dir = DASH / "sections/rooms" / (m.group(1) if m else "-")
    if not room_dir.is_dir() or "  - badges:" not in text:
        continue
    (room_dir / "01-alerts.yaml").write_text(render(list(badges(text))))
    print("wrote", room_dir.name)
